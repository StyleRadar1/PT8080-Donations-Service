-- =============================================================================
-- V5__migrate_garment_type_and_size_enums.sql
-- StyleRadar - Paquete 5: ms-segunda-vida-donaciones (Sprint 3)
-- Migración de registros históricos de tipo_prenda y talla a los nuevos enums:
-- - tipo_prenda: CAMISAS, CAMISETAS, SUETERES, CHAQUETAS, PANTALONES,
--                FALDAS, VESTIDOS, CALZADO, ACCESORIOS
-- - talla:       XS, S, M, L, XL, XXL, TALLA_28..TALLA_42, UNICA
-- =============================================================================

UPDATE publicaciones_segunda_mano
SET tipo_prenda = CASE UPPER(TRIM(tipo_prenda))
    WHEN 'UPPER' THEN 'CAMISAS'
    WHEN 'SUPERIOR' THEN 'CAMISAS'
    WHEN 'CAMISA' THEN 'CAMISAS'
    WHEN 'CAMISAS' THEN 'CAMISAS'
    WHEN 'CAMISETA' THEN 'CAMISETAS'
    WHEN 'CAMISETAS' THEN 'CAMISETAS'
    WHEN 'SUETER' THEN 'SUETERES'
    WHEN 'SUETERES' THEN 'SUETERES'
    WHEN 'SUÉTER' THEN 'SUETERES'
    WHEN 'SUÉTERES' THEN 'SUETERES'
    WHEN 'BUSO' THEN 'SUETERES'
    WHEN 'BUSOS' THEN 'SUETERES'
    WHEN 'BUZO' THEN 'SUETERES'
    WHEN 'BUZOS' THEN 'SUETERES'
    WHEN 'SWEATER' THEN 'SUETERES'
    WHEN 'CHAQUETA' THEN 'CHAQUETAS'
    WHEN 'CHAQUETAS' THEN 'CHAQUETAS'
    WHEN 'ABRIGO' THEN 'CHAQUETAS'
    WHEN 'ABRIGOS' THEN 'CHAQUETAS'
    WHEN 'LOWER' THEN 'PANTALONES'
    WHEN 'INFERIOR' THEN 'PANTALONES'
    WHEN 'PANTALON' THEN 'PANTALONES'
    WHEN 'PANTALÓN' THEN 'PANTALONES'
    WHEN 'PANTALONES' THEN 'PANTALONES'
    WHEN 'JEANS' THEN 'PANTALONES'
    WHEN 'FALDA' THEN 'FALDAS'
    WHEN 'FALDAS' THEN 'FALDAS'
    WHEN 'DRESS' THEN 'VESTIDOS'
    WHEN 'FULL_BODY' THEN 'VESTIDOS'
    WHEN 'CUERPO_COMPLETO' THEN 'VESTIDOS'
    WHEN 'VESTIDO' THEN 'VESTIDOS'
    WHEN 'VESTIDOS' THEN 'VESTIDOS'
    WHEN 'FOOTWEAR' THEN 'CALZADO'
    WHEN 'ZAPATOS' THEN 'CALZADO'
    WHEN 'TENIS' THEN 'CALZADO'
    WHEN 'CALZADO' THEN 'CALZADO'
    WHEN 'ACCESSORY' THEN 'ACCESORIOS'
    WHEN 'ACCESSORIES' THEN 'ACCESORIOS'
    WHEN 'ACCESORIO' THEN 'ACCESORIOS'
    WHEN 'ACCESORIOS' THEN 'ACCESORIOS'
    ELSE tipo_prenda
END
WHERE tipo_prenda IS NOT NULL;

UPDATE publicaciones_segunda_mano
SET talla = CASE UPPER(TRIM(talla))
    WHEN 'ONE_SIZE' THEN 'UNICA'
    WHEN 'TALLA_UNICA' THEN 'UNICA'
    WHEN 'UNICA' THEN 'UNICA'
    WHEN 'ÚNICA' THEN 'UNICA'
    WHEN '28' THEN 'TALLA_28'
    WHEN '30' THEN 'TALLA_30'
    WHEN '32' THEN 'TALLA_32'
    WHEN '34' THEN 'TALLA_34'
    WHEN '36' THEN 'TALLA_36'
    WHEN '37' THEN 'TALLA_37'
    WHEN '38' THEN 'TALLA_38'
    WHEN '39' THEN 'TALLA_39'
    WHEN '40' THEN 'TALLA_40'
    WHEN '41' THEN 'TALLA_41'
    WHEN '42' THEN 'TALLA_42'
    ELSE UPPER(TRIM(talla))
END
WHERE talla IS NOT NULL;
