package edu.dosw.styleradar.donaciones.domain.model;

/**
 * Modalidad de entrega propuesta o acordada para una solicitud de donación benéfica.
 */
public enum DeliveryMode {
    /**
     * Recogida domiciliaria coordinada con el donante en Bogotá D.C.
     */
    HOME_PICKUP,

    /**
     * Entrega física en punto de acopio o sede de la fundación aliada.
     */
    DROP_OFF_POINT
}
